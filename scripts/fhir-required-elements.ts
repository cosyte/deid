/**
 * Regenerates the table of FHIR R4 elements a resource **requires** (`min` of 1 or more) that the
 * FHIR adapter writes a Data Absent Reason in place of when it removes one
 * (`src/fhir/generated/required-elements.ts`).
 *
 * Read from the published R4 (4.0.1) resource definitions at
 * `https://hl7.org/fhir/R4/profiles-resources.json`: every element of every resource
 * `StructureDefinition` whose `min` is 1 or more and whose type is one the pass can remove or empty
 * (a `Reference`, a string or uri kind, a person datatype, an `Attachment`, an `Annotation`, an
 * `Identifier`, a date kind or a backbone element), plus every element that reuses another's
 * definition through `contentReference`, so a nested `Questionnaire.item.item` reads as
 * `Questionnaire.item`. Only element paths are kept, never a description. Nothing reads the network
 * at build, test or run time: this script is run by hand when the table is refreshed, and its
 * output is reviewed and committed.
 *
 *     pnpm exec tsx scripts/fhir-required-elements.ts
 */

import { writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const SOURCE = "https://hl7.org/fhir/R4/profiles-resources.json";

/** The element types the pass can remove, or empty by removing every part of. */
const REMOVABLE_TYPES: ReadonlySet<string> = new Set([
  "Reference",
  "string",
  "markdown",
  "uri",
  "url",
  "Annotation",
  "HumanName",
  "Address",
  "ContactPoint",
  "Attachment",
  "Identifier",
  "date",
  "dateTime",
  "instant",
  "BackboneElement",
]);

interface ElementDefinition {
  readonly path: string;
  readonly min?: number;
  readonly type?: readonly { readonly code: string }[];
  readonly contentReference?: string;
}

interface StructureDefinition {
  readonly resourceType: string;
  readonly kind?: string;
  readonly derivation?: string;
  readonly snapshot?: { readonly element: readonly ElementDefinition[] };
}

interface DefinitionBundle {
  readonly entry: readonly { readonly resource: StructureDefinition }[];
}

async function main(): Promise<void> {
  const response = await fetch(SOURCE, { signal: AbortSignal.timeout(120_000) });
  if (!response.ok) throw new Error(`${SOURCE}: HTTP ${String(response.status)}`);
  const bundle = (await response.json()) as DefinitionBundle;

  const required = new Set<string>();
  const aliases = new Map<string, string>();
  for (const { resource } of bundle.entry) {
    if (resource.resourceType !== "StructureDefinition") continue;
    if (resource.kind !== "resource" || resource.derivation !== "specialization") continue;
    for (const element of resource.snapshot?.element ?? []) {
      if (!element.path.includes(".")) continue;
      if (element.contentReference !== undefined) {
        aliases.set(element.path, element.contentReference.replace(/^.*#/, ""));
      }
      if ((element.min ?? 0) < 1) continue;
      const types =
        element.type?.map((t) => t.code) ??
        (element.contentReference === undefined ? [] : ["BackboneElement"]);
      if (types.some((t) => REMOVABLE_TYPES.has(t))) required.add(element.path);
    }
  }

  const requiredLines = [...required].sort().map((path) => `  ${JSON.stringify(path)},`);
  const choices = new Map<string, string[]>();
  for (const path of required) {
    if (!path.endsWith("[x]")) continue;
    const dot = path.lastIndexOf(".");
    const parent = path.slice(0, dot);
    choices.set(parent, [...(choices.get(parent) ?? []), path.slice(dot + 1, -3)]);
  }
  const choiceLines = [...choices.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([parent, bases]) => `  [${JSON.stringify(parent)}, ${JSON.stringify(bases)}],`);
  const aliasLines = [...aliases.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([from, to]) => `  [${JSON.stringify(from)}, ${JSON.stringify(to)}],`);

  const out = `/**
 * The FHIR R4 elements a resource **requires** (\`min\` of 1 or more) whose type the pass can remove
 * or empty, as the R4 (4.0.1) resource definitions publish them (retrieved from
 * \`${SOURCE}\`). A choice element keeps its \`[x]\`.
 *
 * Generated by \`scripts/fhir-required-elements.ts\`; refresh by running it, never by hand.
 *
 * @packageDocumentation
 * @internal
 */

/** Every required element path, \`Resource.element\` and \`Resource.backbone.element\`. @internal */
export const FHIR_REQUIRED_ELEMENTS: ReadonlySet<string> = new Set<string>([
${requiredLines.join("\n")}
]);

/**
 * The required choice elements of each parent, by the name before \`[x]\`: an instance property
 * \`contentString\` under \`Communication.payload\` is the required \`content[x]\`. @internal
 */
export const FHIR_REQUIRED_CHOICES: ReadonlyMap<string, readonly string[]> = new Map<
  string,
  readonly string[]
>([
${choiceLines.join("\n")}
]);

/**
 * Every element that reuses another element's definition (\`contentReference\`), mapped to the path
 * it reuses, so a nested \`Questionnaire.item.item\` is read as \`Questionnaire.item\`. @internal
 */
export const FHIR_ELEMENT_ALIASES: ReadonlyMap<string, string> = new Map<string, string>([
${aliasLines.join("\n")}
]);
`;
  writeFileSync(join(ROOT, "src/fhir/generated/required-elements.ts"), out);
  process.stdout.write(
    `${String(required.size)} required elements, ${String(aliases.size)} aliases\n`,
  );
}

await main();
